# Generates deterministic synthetic test clips + ground-truth labels for the VAD benchmark.
#
# These are NOT human recordings. They are known-truth signals built to realistic
# speech/noise ratios so the numbers are a faithful measurement of the shipped vad.ts.
# Design rules (so nothing is rigged in our favour):
#   - Room floor is chosen per clip; several clips sit ABOVE the baseline's fixed
#     0.015 RMS threshold (that is the realistic case a fixed threshold fails on).
#   - Speech sits ~12-16 dB above the floor (typical for a talker near a mic).
#   - Breaths sit only ~5-6 dB above the floor (below a +9 dB onset margin).
#   - Speech intervals contain word/gap structure (words ~300 ms, gaps ~120 ms) so
#     hold + hysteresis are actually exercised (a fixed threshold drops out in gaps).
#   - Speech onsets have a ~120 ms attack ramp so onset LATENCY is measurable
#     (a higher trigger threshold necessarily detects a few ms later -- the tradeoff).
import numpy as np, wave, json, os

SR = 44100
rng = np.random.default_rng(11)  # deterministic
HERE = os.path.dirname(os.path.abspath(__file__))
AUD = os.path.join(HERE, "audio")

def noise(n, amp):
    return rng.normal(0, amp, n).astype(np.float32)

def word(n, amp, f0):
    # glottal-ish tone: fundamental + harmonics, plus a little breathiness
    t = np.arange(n) / SR
    sig = np.zeros(n, np.float32)
    for k, g in enumerate([1.0, 0.5, 0.3, 0.15], start=1):
        sig += g * np.sin(2 * np.pi * f0 * k * t)
    sig /= np.max(np.abs(sig) + 1e-9)
    return (sig * amp + noise(n, amp * 0.08)).astype(np.float32)

def breath_burst(n, amp):
    x = noise(n, amp)
    for _ in range(3):                       # low-pass -> breathy, not tonal
        x = np.convolve(x, np.ones(20, np.float32) / 20, mode="same")
    return (x * amp / (np.std(x) + 1e-9)).astype(np.float32)

def build_speech_span(n, floor_amp, peak_amp, f0):
    # word(300ms)+gap(120ms) structure, 120ms attack ramp on the very first sample
    sig = noise(n, floor_amp)                # floor continues through gaps
    word_n, gap_n = int(0.30 * SR), int(0.12 * SR)
    pos, first = 0, True
    while pos < n:
        wn = min(word_n, n - pos)
        w = word(wn, peak_amp, f0)
        if first:                            # attack ramp -> measurable onset latency
            ramp = np.linspace(0, 1, min(int(0.12 * SR), wn), dtype=np.float32)
            w[:len(ramp)] *= ramp
            first = False
        sig[pos:pos + wn] += w
        pos += wn + gap_n                    # leave a floor-only gap between words
    return sig[:n]

def write_wav(path, sig):
    pcm = (np.clip(sig, -1, 1) * 32767).astype(np.int16)
    with wave.open(path, "wb") as w:
        w.setnchannels(1); w.setsampwidth(2); w.setframerate(SR)
        w.writeframes(pcm.tobytes())

def build(dur, floor, segs, kind="speech", peak=0.10, f0=180, breath_amp=0.02):
    n = int(dur * SR)
    sig = noise(n, floor)
    for (a, b) in segs:
        s, e = int(a * SR), int(b * SR)
        if kind == "speech":
            sig[s:e] = build_speech_span(e - s, floor, peak, f0)
        else:  # breath
            sig[s:e] += breath_burst(e - s, breath_amp)
    return sig

# floor chosen relative to baseline's fixed 0.015 threshold; label = ground-truth speech
specs = {
    "clip1-pauses.wav":  dict(dur=12, floor=0.018, segs=[[1.0,3.5],[4.8,7.4],[8.2,11.2]], kind="speech", peak=0.10, label="segs"),
    "clip2-hum.wav":     dict(dur=9,  floor=0.007, segs=[[1.0,8.0]],                        kind="speech", peak=0.05, f0=150, label="segs"),
    "clip3-silence.wav": dict(dur=10, floor=0.022, segs=[],                                 kind="speech", label=[]),
    "clip4-breath.wav":  dict(dur=10, floor=0.010, segs=[[2.0,2.6],[4.0,4.7],[6.5,7.1],[8.5,9.1]], kind="breath", breath_amp=0.020, label=[]),
    "clip5-noisy.wav":   dict(dur=12, floor=0.025, segs=[[1.5,4.0],[5.2,8.0],[9.0,11.5]],   kind="speech", peak=0.13, label="segs"),
    "clip6-quiet.wav":   dict(dur=10, floor=0.006, segs=[[1.2,3.5],[5.0,7.5]],              kind="speech", peak=0.030, label="segs"),
}

labels = {"_comment": "Ground-truth speech intervals. SYNTHETIC clips generated by synth_audio.py (see header)."}
for clip, s in specs.items():
    sig = build(s["dur"], s["floor"], s["segs"], s["kind"], s.get("peak", 0.10),
                s.get("f0", 180), s.get("breath_amp", 0.02))
    write_wav(os.path.join(AUD, clip), sig)
    labels[clip] = {"speech": s["segs"] if s["label"] == "segs" else s["label"]}
    print(f"wrote {clip}  (dur={s['dur']}s floor={s['floor']} kind={s['kind']})")

with open(os.path.join(AUD, "labels.json"), "w") as f:
    json.dump(labels, f, indent=2)
print("wrote labels.json")
